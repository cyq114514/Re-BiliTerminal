    /**共多少个版本。*/
    public static int count() {
        return LOG.length;
    }

    /**第 index 个版本的版本名。*/
    public static String version(int index) {
        return LOG[index][0];
    }

    /**第 index 个版本的更新条目（不含版本名）。*/
    public static String[] items(int index) {
        return Arrays.copyOfRange(LOG[index], 1, LOG[index].length);
    }

    /**当前版本（数据的第一条）的更新条目，供关于页"更新细节"显示。*/
    public static String[] currentItems() {
        return items(0);
    }

    /**按版本名查下标，找不到返回 -1。*/
    public static int indexOf(String version) {
        if (version == null) return -1;
        for (int i = 0; i < LOG.length; i++) {
            if (LOG[i][0].equals(version)) return i;
        }
        return -1;
    }
